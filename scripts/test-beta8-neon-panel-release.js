#!/usr/bin/env node
const fs = require('fs');
function assert(cond, msg) { if (!cond) { console.error(`FAIL: ${msg}`); process.exit(1); } }
const VERSION='5.0.0-beta.9';
assert(fs.readFileSync('VERSION','utf8').trim()===VERSION,'VERSION mismatch');
const rootPkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const rootLock=JSON.parse(fs.readFileSync('package-lock.json','utf8'));
const desktopPkg=JSON.parse(fs.readFileSync('desktop-tauri/package.json','utf8'));
const desktopLock=JSON.parse(fs.readFileSync('desktop-tauri/package-lock.json','utf8'));
const tauri=JSON.parse(fs.readFileSync('desktop-tauri/src-tauri/tauri.conf.json','utf8'));
const rv=JSON.parse(fs.readFileSync('release-versions.json','utf8'));
const openapi=JSON.parse(fs.readFileSync('docs/api/openapi-v2.json','utf8'));
assert(rootPkg.version===VERSION,'root package version mismatch');
assert(rootLock.version===VERSION && rootLock.packages[''].version===VERSION,'root lock mismatch');
assert(desktopPkg.version===VERSION,'desktop package mismatch');
assert(desktopLock.version===VERSION && desktopLock.packages[''].version===VERSION,'desktop lock mismatch');
assert(tauri.version===VERSION,'tauri version mismatch');
assert(rv.application===VERSION,'release-versions app mismatch');
assert(rv.firmware==='5.0.0-beta.6','firmware must remain beta.6');
assert(rv.directApi==='1.0.0','Direct API must remain 1.0.0');
assert(openapi.info.version===VERSION,'OpenAPI mismatch');
const cargo=fs.readFileSync('desktop-tauri/src-tauri/Cargo.toml','utf8');
assert(/\[package\][\s\S]*?version\s*=\s*"5\.0\.0-beta\.9"/m.test(cargo),'Cargo.toml mismatch');
const cargoLock=fs.readFileSync('desktop-tauri/src-tauri/Cargo.lock','utf8');
assert(/\[\[package\]\]\s*\nname\s*=\s*"arduino-led-controller"\s*\nversion\s*=\s*"5\.0\.0-beta\.9"/m.test(cargoLock),'Cargo.lock mismatch');
const wf=fs.readFileSync('.github/workflows/beta-release.yml','utf8');
assert(wf.includes('EXPECTED_VERSION: 5.0.0-beta.9'),'workflow version mismatch');
assert(wf.includes('body_path: docs/v5/BETA8_RELEASE_NOTES.md'),'workflow notes mismatch');
const notes=fs.readFileSync('docs/v5/BETA8_RELEASE_NOTES.md','utf8');
assert(notes.includes('Neon Panel UI Stabilization'),'release title missing');
const theme=fs.readFileSync('desktop-tauri/src/beta7-theme.css','utf8');
assert(theme.includes('Beta.7 local audit responsive grid fix'),'audit fix missing');
const styles=fs.readFileSync('desktop-tauri/src/styles.css','utf8');
assert(styles.includes('.dashboard-time-actions'),'spacing fix missing');
assert(styles.includes('V5 Neon Panel brand mark'),'brand css missing');
assert(styles.includes('.topbar-tagline'),'topbar css missing');
const sidebar=fs.readFileSync('desktop-tauri/src/components/Sidebar.tsx','utf8');
assert(sidebar.includes('/v5-icon.png'),'sidebar icon missing');
const topbar=fs.readFileSync('desktop-tauri/src/components/Topbar.tsx','utf8');
assert(topbar.includes('Arduino LED Controller V5'),'topbar title missing');
assert(topbar.includes('Direct Arduino Control & Automation'),'topbar subtitle missing');
const api=fs.readFileSync('desktop-tauri/src/api/create-desktop-api.ts','utf8');
assert(api.includes('allowPersistentBearer !== true'),'keychain guard missing');
const rust=fs.readFileSync('desktop-tauri/src-tauri/src/lib.rs','utf8');
const a=rust.indexOf('async fn firmware_status('), b=rust.indexOf('async fn firmware_update_inner(',a);
assert(a>=0 && b>a,'firmware boundaries missing');
assert(!rust.slice(a,b).includes('read_profile_ota_password(&config).await'),'firmware check still reads keychain');
assert(rust.slice(b).includes('let password = read_profile_ota_password(&config).await?;'),'secure OTA read missing');
assert(fs.existsSync('docs/assets/v5-neon-panel-presentation.png'),'presentation missing');
assert(fs.existsSync('desktop-tauri/public/v5-icon.png'),'public icon missing');
console.log('BETA8_RELEASE_CONTRACT=PASSED');
