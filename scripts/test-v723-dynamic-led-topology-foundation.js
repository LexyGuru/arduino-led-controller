assert.match(readme,/docs\/v5\/V58_BETA1_INSTALLATION_GUIDE\.md/);
assert.match(readme,/docs\/v5\/V58_BETA1_RELEASE_CHECKLIST\.md/);
assert.match(readme,/RELEASE_NOTES_5\.8\.0-beta\.1\.md/);
