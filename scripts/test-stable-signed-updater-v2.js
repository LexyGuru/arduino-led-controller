#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const cfg=JSON.parse(read('desktop-tauri/src-tauri/tauri.conf.json'));
const build=read('.github/workflows/app-build.yml');
const stable=read('.github/workflows/app-stable-release.yml');
assert.equal(cfg.bundle?.createUpdaterArtifacts,true);
assert.equal(cfg.plugins?.updater?.endpoints?.[0],'https://github.com/LexyGuru/arduino-led-controller/releases/download/updater-stable/latest.json');
assert.ok(cfg.plugins?.updater?.pubkey);
for(const k of ['linux-x86_64','windows-x86_64','macos-apple-silicon','macos-intel']) assert.ok(build.includes(k));
assert.match(build,/TAURI_SIGNING_PRIVATE_KEY/);
assert.match(build,/actions\/upload-artifact@v6/);
assert.doesNotMatch(build,/actions\/upload-artifact@v4/);
assert.match(stable,/Stable release permission and signing preflight/);
assert.match(stable,/RELEASE_PUBLISH_TOKEN/);
assert.match(stable,/releases\/generate-notes/);
assert.match(stable,/Generate signed Stable updater feed/);
assert.match(stable,/gh release (upload|create) updater-stable/);
assert.match(stable,/actions\/download-artifact@v7/);
assert.doesNotMatch(stable,/GH_TOKEN: \$\{\{ github\.token \}\}/);
assert.doesNotMatch(stable,/firmware-beta-release\.yml|firmware-stable-release\.yml/);
console.log('STABLE_UPDATER_TAURI_CONFIG=PASSED');
console.log('STABLE_SIGNED_DESKTOP_ARTIFACTS=PASSED');
console.log('STABLE_RELEASE_PERMISSION_PREFLIGHT=PASSED');
console.log('STABLE_UPDATER_FEED_ALIAS_CONTRACT=PASSED');
console.log('STABLE_SIGNED_UPDATER_PIPELINE=PASSED');
