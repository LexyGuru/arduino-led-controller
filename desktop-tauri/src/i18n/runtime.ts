export const languageOptions: AppLanguage[] = ['hu', 'en', 'de'];
const storageKey = 'arduino-led-controller.language';
let activeLanguage: AppLanguage = detectLanguage();

export function detectLanguage(): AppLanguage {
  const stored = globalThis.localStorage?.getItem(storageKey);
  if (stored && languageOptions.includes(stored as AppLanguage)) return stored as AppLanguage;
  const locale = globalThis.navigator?.language?.toLowerCase() ?? '';
  if (locale.startsWith('de')) return 'de';
  if (locale.startsWith('hu')) return 'hu';
  return 'en';
}

function interpolate(text: string, values?: Record<string, string | number>) {
  return text.replace(/{{\s*([^}\s]+)\s*}}/g, (_, key: string) => String(values?.[key] ?? `{{${key}}}`));
}


export function setActiveLanguage(language: AppLanguage) {
  activeLanguage = language;
  globalThis.localStorage?.setItem(storageKey, language);
}

export function translateFor(language: AppLanguage, key: string, values?: Record<string, string | number>) {
  return interpolate(dictionaries[language][key] ?? dictionaries.hu[key] ?? key, values);
}

export function translate(key: string, values?: Record<string, string | number>) {
  return translateFor(activeLanguage, key, values);
}

