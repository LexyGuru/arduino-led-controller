const supported: AppLanguage[] = ['hu', 'en', 'de'];
const storageKey = 'arduino-led-controller.language';
let activeLanguage: AppLanguage = detectLanguage();

function detectLanguage(): AppLanguage {
  const stored = globalThis.localStorage?.getItem(storageKey);
  if (stored && supported.includes(stored as AppLanguage)) return stored as AppLanguage;
  const locale = globalThis.navigator?.language?.toLowerCase() ?? '';
  if (locale.startsWith('de')) return 'de';
  if (locale.startsWith('hu')) return 'hu';
  return 'en';
}

function interpolate(text: string, values?: Record<string, string | number>) {
  return text.replace(/{{\s*([^}\s]+)\s*}}/g, (_, key: string) => String(values?.[key] ?? `{{${key}}}`));
}

interface I18nValue { language: AppLanguage; setLanguage: (language: AppLanguage) => void; t: (key: string, values?: Record<string, string | number>) => string; }
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<AppLanguage>(() => activeLanguage);
  const setLanguage = (next: AppLanguage) => { activeLanguage = next; updateLanguage(next); globalThis.localStorage?.setItem(storageKey, next); };
  useEffect(() => { activeLanguage = language; document.documentElement.lang = language; }, [language]);
  const value = useMemo<I18nValue>(() => ({ language, setLanguage, t: (key, values) => interpolate(dictionaries[language][key] ?? dictionaries.hu[key] ?? key, values) }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}

export function translate(key: string, values?: Record<string, string | number>) {
  return interpolate(dictionaries[activeLanguage][key] ?? dictionaries.hu[key] ?? key, values);
}

